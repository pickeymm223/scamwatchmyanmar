let LANG = "mm";
try { LANG = localStorage.getItem("sw_lang") || "mm"; } catch (e) {}
if (!I18N[LANG]) LANG = "mm";

function t(k) {
  return (I18N[LANG] && I18N[LANG][k] != null) ? I18N[LANG][k]
       : (I18N.mm[k] != null ? I18N.mm[k] : k);
}

function applyLang() {
  document.documentElement.lang = {mm: "my", en: "en", cn: "zh", th: "th", jp: "ja"}[LANG] || LANG;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.innerHTML = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = t(el.getAttribute("data-i18n-ph"));
  });
  const _sel = document.querySelector(".langsel");
  if (_sel) _sel.value = LANG;
  if (I18N[LANG].title) document.title = t("title");
  const md = document.querySelector('meta[name="description"]');
  if (md && I18N[LANG].meta_desc) md.setAttribute("content", t("meta_desc"));
  // dynamic content re-render (index page only)
  if (typeof ROWS !== "undefined" && typeof renderStats === "function" && ROWS.length) {
    renderStats();
    const q = document.getElementById("q");
    if (q && q.value.trim() && typeof renderResult === "function") renderResult(q.value);
  }
}

function setLang(l) {
  if (!I18N[l]) return;
  LANG = l;
  try { localStorage.setItem("sw_lang", l); } catch (e) {}
  applyLang();
}

document.addEventListener("DOMContentLoaded", () => {
  const _sel = document.querySelector(".langsel");
  if (_sel) {
    _sel.value = LANG;
    _sel.addEventListener("change", () => setLang(_sel.value));
  }
  applyLang();
});
